export function searchKeywords(query: string, niche?: string): KeywordRecord[] {
  const q = query.trim().toLowerCase();
  return KEYWORDS.filter((k) => {
    const nicheOk = !niche || niche === "All" || k.niche === niche;
    if (!q) return nicheOk;
    const hay = `${k.keyword} ${k.niche} ${k.related.join(" ")} ${k.notes}`.toLowerCase();
    return nicheOk && hay.includes(q);
  }).sort((a, b) => b.overallScore - a.overallScore);
}

export function getKeyword(keyword: string): KeywordRecord | undefined {
  const q = keyword.toLowerCase();
  return KEYWORDS.find((k) => k.keyword === q) ?? KEYWORDS.find((k) => k.keyword.includes(q));
}

export function niches(): string[] {
  return ["All", ...Array.from(new Set(KEYWORDS.map((k) => k.niche))).sort()];
}
